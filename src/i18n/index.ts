const dictionaries: Record<Locale, Record<MessageKey, string>> = { ru, en };
export const translate = (locale: Locale) => (key: MessageKey) =>
  dictionaries[locale]?.[key] ?? ru[key];
export function stepLabel(step: RouteStep, locale: Locale): string {
  const t = translate(locale);
  if (step.instruction) return localize(step.instruction, locale);
  const keys: Record<RouteStep["kind"], MessageKey> = {
    start: "startStep",
    straight: "straightStep",
    left: "leftStep",
    right: "rightStep",
    stairsUp: "upStep",
    stairsDown: "downStep",
    lift: "liftStep",
    arrive: "arriveStep",
    passage: "passageStep",
  };
  return (
    t(keys[step.kind]) + (step.toFloor !== undefined ? ` ${step.toFloor}` : "")
  );
}
export const messages = dictionaries;
